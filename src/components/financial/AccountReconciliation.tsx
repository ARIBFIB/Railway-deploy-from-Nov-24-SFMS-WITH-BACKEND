import React, { useState, useRef, useEffect } from 'react';
import { Button } from '../Button';
import { Input } from '../Input';
import {
  Printer,
  Upload,
  Calendar,
  ChevronDown,
  Eye,
  EyeOff,
  FileText,
  BarChart3,
  Grid,
  X,
  MessageSquare,
  CheckCircle,
  AlertCircle
} from 'lucide-react';
import { verificationSeriesService, type VerificationSeriesItem } from '../../services/verificationSeriesService';
import { ReconciliationService } from '../../services/reconciliationService';

// This component implements the account reconciliation functionality where accounting transactions 
// are populated only after a verification has been created and posted. The table is built from 
// posted ledger entries generated by verifications that use coding templates. When a verification 
// is saved with a valid coding template, the system records debit and credit entries against 
// selected accounts with verification date and series. When the user enters account number, 
// matching reconciliation period, open-posts-from date, and verification series and executes 
// the search, the system retrieves those posted entries and displays them in the Accounting 
// transactions table for reconciliation.

interface Transaction {
  id: string;
  date: string;
  description: string;
  amount: number;
  selected: boolean;
  matched: boolean;
  voucher_number?: string;
  comment?: string;
}

interface ReconciliationData {
  account: string;
  reconciliationPeriodStart: string;
  reconciliationPeriodEnd: string;
  openRecordsFrom: string;
  verificationSeries: string;
  accountingTransactions: Transaction[];
  loadedTransactions: Transaction[];
}

export const AccountReconciliation: React.FC = () => {
  const [data, setData] = useState<ReconciliationData>({
    account: '',
    reconciliationPeriodStart: '',
    reconciliationPeriodEnd: new Date().toISOString().split('T')[0],
    openRecordsFrom: '',
    verificationSeries: '',
    accountingTransactions: [],
    loadedTransactions: []
  });

  const [selectAllAccounting, setSelectAllAccounting] = useState(false);
  const [selectAllLoaded, setSelectAllLoaded] = useState(false);
  const [loading, setLoading] = useState(false);
  const [batchDate, setBatchDate] = useState(new Date().toISOString().split('T')[0]);

  const [verificationSeries, setVerificationSeries] = useState<VerificationSeriesItem[]>([]);
  const [loadingSeries, setLoadingSeries] = useState(true);

  const [hideMatched, setHideMatched] = useState(false);
  const [showHistoryPopup, setShowHistoryPopup] = useState(false);
  const [showBatchReconciliationPopup, setShowBatchReconciliationPopup] = useState(false);
  const [showAccountAnalysisPopup, setShowAccountAnalysisPopup] = useState(false);
  const [showReconciliationReportPopup, setShowReconciliationReportPopup] = useState(false);
  const [activeTransactionFilter, setActiveTransactionFilter] = useState('Reconciled');
  const [customerPaymentsFilter, setCustomerPaymentsFilter] = useState('Yes');
  const [supplierPaymentsFilter, setSupplierPaymentsFilter] = useState('Yes');
  const [otherItemsFilter, setOtherItemsFilter] = useState('Yes');
  const [toast, setToast] = useState<{ message: string; type: 'success' | 'error' | 'info'; visible: boolean }>({
    message: '',
    type: 'info',
    visible: false
  });
  const [activeCommentRow, setActiveCommentRow] = useState<{ id: string; type: 'accounting' | 'loaded' } | null>(null);
  const [commentText, setCommentText] = useState('');
  const [analysisDateFrom, setAnalysisDateFrom] = useState('');
  const [analysisDateTo, setAnalysisDateTo] = useState('');
  const fileInputRef = useRef<HTMLInputElement>(null);

  const showToast = (message: string, type: 'success' | 'error' | 'info' = 'info') => {
    setToast({ message, type, visible: true });
    setTimeout(() => {
      setToast(prev => ({ ...prev, visible: false }));
    }, 5000);
  };

  const handleInputChange = (field: keyof ReconciliationData, value: string) => {
    setData(prev => ({
      ...prev,
      [field]: value
    }));
  };

  const handleTransactionSelect = (type: 'accounting' | 'loaded', transactionId: string) => {
    setData(prev => ({
      ...prev,
      [type === 'accounting' ? 'accountingTransactions' : 'loadedTransactions']:
        prev[type === 'accounting' ? 'accountingTransactions' : 'loadedTransactions'].map(t =>
          t.id === transactionId ? { ...t, selected: !t.selected } : t
        )
    }));
  };

  const handleSearch = async () => {
    setLoading(true);
    try {
      console.log('Searching with filters:', data);

      // Fetch ledger entries from API based on the selected criteria
      const response = await ReconciliationService.getLedgerEntries({
        account: data.account.trim(),
        start_date: data.reconciliationPeriodStart,
        end_date: data.reconciliationPeriodEnd,
        verification_series: data.verificationSeries
      });

      if (response.success) {
        console.log('Received ledger entries:', response.data);
        // Update the state with the fetched data
        setData(prev => ({
          ...prev,
          accountingTransactions: response.data.accountingTransactions,
          loadedTransactions: response.data.loadedTransactions
        }));

        // Reset selection states
        setSelectAllAccounting(false);
        setSelectAllLoaded(false);
      } else {
        console.error('Failed to fetch ledger entries:', response.message);
      }
    } catch (error) {
      console.error('Error fetching ledger entries:', error);
      // In a real implementation, you might want to show an error message to the user
    } finally {
      setLoading(false);
    }
  };


  const handleHideMatched = () => {
    setHideMatched(!hideMatched);
  };

  const handleLoadHistory = () => {
    setShowHistoryPopup(true);
  };

  const handleMassReconciliation = () => {
    setShowBatchReconciliationPopup(true);
  };

  const executeBatchReconciliation = (action: 'reconcile' | 'undo') => {
    if (data.accountingTransactions.length === 0) {
      showToast("No transactions were found in the selected period.", "info");
      return;
    }

    const hasSelection = data.accountingTransactions.some(t => t.selected);
    const dateRange = `${data.reconciliationPeriodStart || ''} - ${data.reconciliationPeriodEnd || ''}`;

    if (action === 'reconcile') {
      if (hasSelection) {
        showToast("No transactions were found in the selected period.", "info");
        return;
      }
      setData(prev => ({
        ...prev,
        accountingTransactions: prev.accountingTransactions.map(t => ({ ...t, selected: true }))
      }));
      showToast(`Mass reconciliation conducted for period ${dateRange}`, "success");
    } else {
      if (!hasSelection) {
        showToast("No transactions were found in the selected period.", "info");
        return;
      }
      setData(prev => ({
        ...prev,
        accountingTransactions: prev.accountingTransactions.map(t => ({ ...t, selected: false }))
      }));
      showToast(`Mass reconciliation has been regressed for period ${dateRange}`, "success");
    }
    setShowBatchReconciliationPopup(false);
  };

  const handleOpenComment = (id: string, type: 'accounting' | 'loaded') => {
    const transaction = data[type === 'accounting' ? 'accountingTransactions' : 'loadedTransactions'].find(t => t.id === id);
    setCommentText(transaction?.comment || '');
    setActiveCommentRow({ id, type });
  };

  const handleSaveComment = async () => {
    if (!activeCommentRow) return;
    const { id, type } = activeCommentRow;

    // Update local state first for immediate feedback
    setData(prev => ({
      ...prev,
      [type === 'accounting' ? 'accountingTransactions' : 'loadedTransactions']:
        prev[type === 'accounting' ? 'accountingTransactions' : 'loadedTransactions'].map(t =>
          t.id === id ? { ...t, comment: commentText } : t
        )
    }));

    try {
      // For accounting transactions, persist to backend
      if (type === 'accounting') {
        const response = await ReconciliationService.updateComment(id, commentText);
        if (response.success) {
          showToast("Comment saved successfully", "success");
        }
      } else {
        // Loaded transactions (bank file) don't have persistence yet
        showToast("Comment updated (Local)", "info");
      }
    } catch (error) {
      console.error('Error saving comment:', error);
      showToast("Failed to save comment to server", "error");
    }

    setActiveCommentRow(null);
    setCommentText('');
  };

  const handleAccountAnalysis = () => {
    setAnalysisDateFrom(data.reconciliationPeriodStart);
    setAnalysisDateTo(data.reconciliationPeriodEnd);
    setShowAccountAnalysisPopup(true);
  };

  const handleReconciliationReport = () => {
    setShowReconciliationReportPopup(true);
  };

  const generateAccountAnalysisReport = (format: 'screen' | 'pdf' | 'txt') => {
    const transactions = activeTransactionFilter === 'All'
      ? data.accountingTransactions
      : activeTransactionFilter === 'Reconciled'
        ? data.accountingTransactions.filter(t => t.selected)
        : data.accountingTransactions.filter(t => !t.selected);

    const reportData = {
      transactions,
      account: data.account,
      dateFrom: analysisDateFrom,
      dateTo: analysisDateTo,
      printDate: new Date().toLocaleDateString(),
      printTime: new Date().toLocaleTimeString(),
      companyName: "Company Name",
      systemVersion: "v1.0.0"
    };

    let runningBalance = 0;
    let totalDebit = 0;
    let totalCredit = 0;

    const rows = transactions.map(t => {
      const debit = t.amount > 0 ? t.amount : 0;
      const credit = t.amount < 0 ? Math.abs(t.amount) : 0;
      totalDebit += debit;
      totalCredit += credit;
      runningBalance += t.amount;
      return { ...t, debit, credit, runningBalance };
    });

    if (format === 'txt') {
      const content = `ACCOUNT ANALYSIS REPORT\n` +
        `Company: ${reportData.companyName}\n` +
        `Period: ${reportData.dateFrom} to ${reportData.dateTo}\n` +
        `Account: ${reportData.account}\n\n` +
        `Ver. No. | Date | Description | Debit | Credit | Balance\n` +
        transactions.map(t => `${t.voucher_number || ''} | ${t.date} | ${t.description} | ${t.amount > 0 ? t.amount.toFixed(2) : ''} | ${t.amount < 0 ? Math.abs(t.amount).toFixed(2) : ''}`).join('\n');

      const blob = new Blob([content], { type: 'text/plain' });
      const url = URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = url;
      a.download = `AccountAnalysis_${reportData.account}.txt`;
      a.click();
      return;
    }

    const htmlContent = `
      <html>
        <head>
          <title>Account Analysis Report</title>
          <style>
            body { font-family: sans-serif; padding: 20px; }
            .header { display: flex; justify-content: space-between; margin-bottom: 30px; }
            .title { text-align: center; font-weight: bold; }
            table { width: 100%; border-collapse: collapse; margin-top: 20px; }
            th, td { border: 1px solid #ccc; padding: 8px; text-align: left; }
            .right { text-align: right; }
          </style>
        </head>
        <body>
          <div class="header">
            <div>
              <strong>${reportData.companyName}</strong><br/>
              Period: ${reportData.dateFrom} - ${reportData.dateTo}
            </div>
            <div class="title">
              <h2>Account Analysis</h2>
              Account: ${reportData.account}
            </div>
            <div class="right">
              Date: ${reportData.printDate}<br/>
              Time: ${reportData.printTime}<br/>
              Version: ${reportData.systemVersion}
            </div>
          </div>
          <table>
            <thead>
              <tr>
                <th>Ver. No</th>
                <th>Date</th>
                <th>Description</th>
                <th class="right">Debit</th>
                <th class="right">Credit</th>
                <th class="right">Balance</th>
              </tr>
            </thead>
            <tbody>
              ${rows.map(t => `
                <tr>
                  <td>${t.voucher_number || ''}</td>
                  <td>${t.date}</td>
                  <td>${t.description}</td>
                  <td class="right">${t.debit > 0 ? t.debit.toLocaleString('sv-SE', { minimumFractionDigits: 2 }) : ''}</td>
                  <td class="right">${t.credit > 0 ? t.credit.toLocaleString('sv-SE', { minimumFractionDigits: 2 }) : ''}</td>
                  <td class="right">${t.runningBalance.toLocaleString('sv-SE', { minimumFractionDigits: 2 })}</td>
                </tr>
              `).join('')}
            </tbody>
            <tfoot>
              <tr style="font-weight: bold; background-color: #f9fafb;">
                <td colspan="3">Account Total</td>
                <td class="right">${totalDebit.toLocaleString('sv-SE', { minimumFractionDigits: 2 })}</td>
                <td class="right">${totalCredit.toLocaleString('sv-SE', { minimumFractionDigits: 2 })}</td>
                <td class="right">${runningBalance.toLocaleString('sv-SE', { minimumFractionDigits: 2 })}</td>
              </tr>
            </tfoot>
          </table>
          <div style="margin-top: 30px; font-size: 0.9em; color: #666;">
            <strong>Account Analysis Report Description:</strong><br/>
            This report provides a detailed overview of transactions for the specified account within the selected period...
          </div>
        </body>
      </html>
    `;

    const newTab = window.open();
    if (newTab) {
      newTab.document.write(htmlContent);
      if (format === 'pdf') {
        newTab.print();
      }
    }
  };

  const handleLoadFile = () => {
    if (fileInputRef.current) {
      fileInputRef.current.click();
    }
  };

  // Load verification series from settings
  useEffect(() => {
    const loadVerificationSeries = async () => {
      try {
        setLoadingSeries(true);
        const selectedSeries = await verificationSeriesService.getSelectedSeries('accounting');
        setVerificationSeries(selectedSeries);

        // If there are series and none is selected yet, select the first one
        if (selectedSeries.length > 0 && !data.verificationSeries) {
          setData(prev => ({
            ...prev,
            verificationSeries: selectedSeries[0].code
          }));
        }
      } catch (error) {
        console.error('Failed to load verification series:', error);
        // Set some default series if API fails
        setVerificationSeries([
          { id: '1', code: 'A - Accounting', name: 'Accounting', manualAccounting: true, position: 0 },
          { id: '2', code: 'C - Cash', name: 'Cash', manualAccounting: true, position: 1 },
          { id: '3', code: 'F - Finance', name: 'Finance', manualAccounting: true, position: 2 },
          { id: '4', code: 'G - General', name: 'General', manualAccounting: true, position: 3 },
          { id: '5', code: 'K - Kreditor', name: 'Kreditor', manualAccounting: true, position: 4 }
        ]);
      } finally {
        setLoadingSeries(false);
      }
    };

    loadVerificationSeries();
  }, []);

  // Handle select all for accounting transactions
  const handleSelectAllAccounting = () => {
    const allSelected = !selectAllAccounting;
    setSelectAllAccounting(allSelected);

    setData(prev => ({
      ...prev,
      accountingTransactions: prev.accountingTransactions.map(t => ({
        ...t,
        selected: allSelected
      }))
    }));
  };

  // Handle select all for loaded transactions
  const handleSelectAllLoaded = () => {
    const allSelected = !selectAllLoaded;
    setSelectAllLoaded(allSelected);

    setData(prev => ({
      ...prev,
      loadedTransactions: prev.loadedTransactions.map(t => ({
        ...t,
        selected: allSelected
      }))
    }));
  };

  // Update select all states when transactions change
  useEffect(() => {
    const allAccountingSelected = data.accountingTransactions.length > 0 &&
      data.accountingTransactions.every(t => t.selected);
    setSelectAllAccounting(allAccountingSelected);

    const allLoadedSelected = data.loadedTransactions.length > 0 &&
      data.loadedTransactions.every(t => t.selected);
    setSelectAllLoaded(allLoadedSelected);
  }, [data.accountingTransactions, data.loadedTransactions]);

  const handleSave = () => {
    console.log('Saving reconciliation...');
    showToast("Reconciliation complete.", "success");
  };

  const handleCancel = () => {
    console.log('Canceling reconciliation...');
  };

  const calculateBalance = (transactions: Transaction[]) => {
    return transactions.reduce((sum, t) => sum + t.amount, 0);
  };

  const calculateSelectedTotal = (transactions: Transaction[]) => {
    return transactions
      .filter(t => t.selected)
      .reduce((sum, t) => sum + t.amount, 0);
  };

  const calculateClosingBalance = (transactions: Transaction[]) => {
    const balance = calculateBalance(transactions);
    const selected = calculateSelectedTotal(transactions);
    return balance + selected;
  };

  const filteredAccountingTransactions = hideMatched
    ? data.accountingTransactions.filter(t => !t.matched)
    : data.accountingTransactions;

  const filteredLoadedTransactions = hideMatched
    ? data.loadedTransactions.filter(t => !t.matched)
    : data.loadedTransactions;

  const accountingBalance = calculateBalance(data.accountingTransactions);
  const loadedBalance = calculateBalance(data.loadedTransactions);
  const accountingSelected = calculateSelectedTotal(data.accountingTransactions);
  const loadedSelected = calculateSelectedTotal(data.loadedTransactions);
  const accountingClosing = calculateClosingBalance(data.accountingTransactions);
  const loadedClosing = calculateClosingBalance(data.loadedTransactions);

  return (
    <div className="space-y-6">

      {/* Header */}
      <div className="mb-4">
        <h1 className="text-2xl font-bold text-gray-900 uppercase">RECONCILE ACCOUNT</h1>
      </div>

      {/* Action Buttons */}
      <div className="py-4">
        <div className="flex items-center space-x-4">
          <Button
            variant="ghost"
            onClick={() => console.log('View all clicked')}
            className="flex items-center space-x-1 text-xs text-gray-700 hover:text-[#5c6f2b] p-1 h-8"
          >
            <Grid className="w-3 h-3" />
            <span>View all</span>
          </Button>
          <Button
            variant="ghost"
            onClick={handleHideMatched}
            className="flex items-center space-x-1 text-xs text-gray-700 hover:text-[#5c6f2b] p-1 h-8"
          >
            {hideMatched ? <EyeOff className="w-3 h-3" /> : <Eye className="w-3 h-3" />}
            <span>Hide matched</span>
          </Button>
          <Button
            variant="ghost"
            onClick={handleLoadHistory}
            className="flex items-center space-x-1 text-xs text-gray-700 hover:text-[#5c6f2b] p-1 h-8"
          >
            <FileText className="w-3 h-3" />
            <span>Reading history</span>
          </Button>
          <Button
            variant="ghost"
            onClick={handleMassReconciliation}
            className="flex items-center space-x-1 text-xs text-gray-700 hover:text-[#5c6f2b] p-1 h-8"
          >
            <BarChart3 className="w-3 h-3" />
            <span>Batch reconciliation</span>
          </Button>
          <Button
            variant="ghost"
            onClick={handleAccountAnalysis}
            className="flex items-center space-x-1 text-xs text-gray-700 hover:text-[#5c6f2b] p-1 h-8"
          >
            <Printer className="w-3 h-3" />
            <span>Account analysis</span>
          </Button>
          <Button
            variant="ghost"
            onClick={handleReconciliationReport}
            className="flex items-center space-x-1 text-xs text-gray-700 hover:text-[#5c6f2b] p-1 h-8"
          >
            <Printer className="w-3 h-3" />
            <span>Reconciliation report</span>
          </Button>
          <Button
            variant="ghost"
            onClick={handleLoadFile}
            className="flex items-center space-x-1 text-xs text-gray-700 hover:text-[#5c6f2b] p-1 h-8"
          >
            <Upload className="w-3 h-3" />
            <span>Read the file</span>
          </Button>
        </div>
      </div>

      {/* Filter Section */}
      <div className="py-4 bg-gray-50">
        <div className="grid grid-cols-5 gap-4">
          <div className="space-y-2">
            <label className="block text-sm font-medium text-gray-700">Account</label>
            <Input
              value={data.account}
              onChange={(e) => handleInputChange('account', e.target.value)}
              className="w-full"
            />
          </div>
          <div className="space-y-2">
            <label className="block text-sm font-medium text-gray-700">Reconciliation period</label>
            <div className="relative">
              <Calendar className="absolute left-3 top-1/2 transform -translate-y-1/2 text-gray-400 w-4 h-4" />
              <Input
                type="date"
                value={data.reconciliationPeriodStart}
                onChange={(e) => handleInputChange('reconciliationPeriodStart', e.target.value)}
                className="pl-10 w-full"
              />
            </div>
          </div>
          <div className="space-y-2">
            <label className="block text-sm font-medium text-gray-700">Reconciliation period to</label>
            <div className="relative">
              <Calendar className="absolute left-3 top-1/2 transform -translate-y-1/2 text-gray-400 w-4 h-4" />
              <Input
                type="date"
                value={data.reconciliationPeriodEnd}
                onChange={(e) => handleInputChange('reconciliationPeriodEnd', e.target.value)}
                className="pl-10 w-full"
              />
            </div>
          </div>
          <div className="space-y-2">
            <label className="block text-sm font-medium text-gray-700">Open records from</label>
            <div className="relative">
              <Calendar className="absolute left-3 top-1/2 transform -translate-y-1/2 text-gray-400 w-4 h-4" />
              <Input
                type="date"
                value={data.openRecordsFrom}
                onChange={(e) => handleInputChange('openRecordsFrom', e.target.value)}
                className="pl-10 w-full"
              />
            </div>
          </div>
          <div className="space-y-2">
            <label className="block text-sm font-medium text-gray-700">Verification series:</label>
            <div className="relative">
              {loadingSeries ? (
                <div className="w-full px-3 py-2 border border-gray-300 rounded-md bg-gray-100">
                  Loading...
                </div>
              ) : (
                <select
                  value={data.verificationSeries}
                  onChange={(e) => handleInputChange('verificationSeries', e.target.value)}
                  className="w-full px-3 py-2 border border-gray-300 rounded-md focus:outline-none focus:ring-2 focus:ring-blue-500"
                >
                  {verificationSeries.map((series) => (
                    <option key={series.id} value={series.code}>
                      {series.code} - {series.name}
                    </option>
                  ))}
                </select>
              )}
            </div>
            <Button
              onClick={handleSearch}
              className="bg-gray-800 hover:bg-gray-900 text-white w-full mt-2"
              disabled={loading || !data.account || !data.reconciliationPeriodStart || !data.reconciliationPeriodEnd || !data.verificationSeries}
            >
              {loading ? 'Searching...' : 'Search'}
            </Button>
          </div>
        </div>
      </div>

      {/* Main Content - Two Column Layout */}
      <div className="flex-1 py-6">
        <div className="grid grid-cols-2 gap-6">
          {/* Left Column - Accounting Transactions */}
          <div>
            <div className="mb-2">
              <h3 className="text-sm font-medium text-gray-900 inline mr-4">Accounting transactions</h3>
              <span className="text-sm text-gray-600">
                {data.accountingTransactions.length > 0 ? 'Opening account balance: 0,00' : 'Opening account balance: 0,00'}</span>
            </div>
            <div className="text-sm text-gray-600 mb-2">
              {data.reconciliationPeriodStart ? new Date(data.reconciliationPeriodStart).toLocaleDateString('en-US', { month: 'long', year: 'numeric' }) : ''}
            </div>
            <div className="border border-gray-300 rounded-lg">
              <div className="overflow-y-auto max-h-96">
                <table className="min-w-full divide-y divide-gray-200">
                  <thead className="bg-gray-50">
                    <tr>
                      <th scope="col" className="px-4 py-2 text-left text-xs font-medium text-gray-500 uppercase tracking-wider w-12">
                        <input
                          type="checkbox"
                          checked={selectAllAccounting}
                          onChange={handleSelectAllAccounting}
                          className="h-4 w-4 text-[#5c6f2b] rounded border-gray-300 focus:ring-[#5c6f2b]/50"
                        />
                      </th>
                      <th scope="col" className="px-4 py-2 text-left text-xs font-medium text-gray-500 uppercase tracking-wider">Verification no.</th>
                      <th scope="col" className="px-4 py-2 text-left text-xs font-medium text-gray-500 uppercase tracking-wider">Date</th>
                      <th scope="col" className="px-4 py-2 text-left text-xs font-medium text-gray-500 uppercase tracking-wider">Description</th>
                      <th scope="col" className="px-4 py-2 text-right text-xs font-medium text-gray-500 uppercase tracking-wider">Amount</th>
                      <th scope="col" className="px-4 py-2 text-center text-xs font-medium text-gray-500 uppercase tracking-wider w-10">Comment</th>
                    </tr>
                  </thead>
                  <tbody className="bg-white divide-y divide-gray-200">
                    {data.accountingTransactions.length > 0 ? (
                      data.accountingTransactions.map((transaction) => (
                        <tr
                          key={transaction.id}
                          className={`hover:bg-[#dddddd] bg-white ${transaction.selected ? 'bg-blue-100' : ''}`}
                          onClick={() => handleTransactionSelect('accounting', transaction.id)}
                        >
                          <td className="px-4 py-2 whitespace-nowrap text-sm text-gray-900 w-12">
                            <input
                              type="checkbox"
                              checked={transaction.selected}
                              onChange={() => handleTransactionSelect('accounting', transaction.id)}
                              className="h-4 w-4 text-[#5c6f2b] rounded border-gray-300 focus:ring-[#5c6f2b]/50"
                              onClick={(e) => {
                                e.stopPropagation();
                              }}
                            />
                          </td>
                          <td className="px-4 py-2 whitespace-nowrap text-sm text-gray-900">{transaction.voucher_number || '&nbsp;'}</td>
                          <td className="px-4 py-2 whitespace-nowrap text-sm text-gray-900">{transaction.date}</td>
                          <td className="px-4 py-2 text-sm text-gray-900">{transaction.description}</td>
                          <td className="px-4 py-2 whitespace-nowrap text-sm text-right text-gray-900">
                            {transaction.amount < 0
                              ? `-${Math.abs(transaction.amount).toLocaleString('sv-SE', { minimumFractionDigits: 2 })}`
                              : transaction.amount.toLocaleString('sv-SE', { minimumFractionDigits: 2 })}
                          </td>
                          <td className="px-4 py-2 whitespace-nowrap text-center text-gray-400">
                            <button
                              onClick={(e) => { e.stopPropagation(); handleOpenComment(transaction.id, 'accounting'); }}
                              className={`hover:text-blue-500 ${transaction.comment ? 'text-blue-500' : ''}`}
                            >
                              <MessageSquare className="w-4 h-4" />
                            </button>
                          </td>
                        </tr>
                      ))
                    ) : (
                      <tr>
                        <td colSpan={6} className="px-4 py-8 text-center text-sm text-gray-500">
                          {loading ? 'Loading transactions...' : 'No accounting transactions found. Search to populate this table after creating and posting verifications.'}
                        </td>
                      </tr>
                    )}
                  </tbody>
                </table>
              </div>
            </div>
            <div className="border-t border-gray-300 mt-2">
              <div className="text-sm text-gray-600 text-right">
                {data.accountingTransactions.length > 0
                  ? `Account balance per ${data.reconciliationPeriodEnd || '-'}: ${calculateBalance(data.accountingTransactions).toLocaleString('sv-SE', { minimumFractionDigits: 2 })}`
                  : 'Account balance per -'}
              </div>
            </div>
          </div>

          {/* Right Column - Loaded Transactions */}
          <div>
            <div className="mb-2">
              <h3 className="text-sm font-medium text-gray-900 inline mr-4">Loaded transactions</h3>
              <span className="text-sm text-gray-600">
                {data.loadedTransactions.length > 0 ? 'Opening account balance: 0,00' : 'Opening account balance: -'}</span>
            </div>
            <div className="text-sm text-gray-600 mb-2">
              {data.reconciliationPeriodStart ? new Date(data.reconciliationPeriodStart).toLocaleDateString('en-US', { month: 'long', year: 'numeric' }) : ''}
            </div>
            <div className="border border-gray-300 rounded-lg">
              <div className="overflow-y-auto max-h-96">
                <table className="min-w-full divide-y divide-gray-200">
                  <thead className="bg-gray-50">
                    <tr>
                      <th scope="col" className="px-4 py-2 text-left text-xs font-medium text-gray-500 uppercase tracking-wider w-12">
                        <input
                          type="checkbox"
                          checked={selectAllLoaded}
                          onChange={handleSelectAllLoaded}
                          className="h-4 w-4 text-[#5c6f2b] rounded border-gray-300 focus:ring-[#5c6f2b]/50"
                        />
                      </th>
                      <th scope="col" className="px-4 py-2 text-left text-xs font-medium text-gray-500 uppercase tracking-wider">Verification no.</th>
                      <th scope="col" className="px-4 py-2 text-left text-xs font-medium text-gray-500 uppercase tracking-wider">Date</th>
                      <th scope="col" className="px-4 py-2 text-left text-xs font-medium text-gray-500 uppercase tracking-wider">Description</th>
                      <th scope="col" className="px-4 py-2 text-right text-xs font-medium text-gray-500 uppercase tracking-wider">Amount</th>
                      <th scope="col" className="px-4 py-2 text-center text-xs font-medium text-gray-500 uppercase tracking-wider w-10">Comment</th>
                    </tr>
                  </thead>
                  <tbody className="bg-white divide-y divide-gray-200">
                    {data.loadedTransactions.length > 0 ? (
                      data.loadedTransactions.map((transaction) => (
                        <tr
                          key={transaction.id}
                          className={`hover:bg-[#dddddd] bg-white ${transaction.selected ? 'bg-blue-100' : ''}`}
                          onClick={() => handleTransactionSelect('loaded', transaction.id)}
                        >
                          <td className="px-4 py-2 whitespace-nowrap text-sm text-gray-900 w-12">
                            <input
                              type="checkbox"
                              checked={transaction.selected}
                              onChange={() => handleTransactionSelect('loaded', transaction.id)}
                              className="h-4 w-4 text-[#5c6f2b] rounded border-gray-300 focus:ring-[#5c6f2b]/50"
                              onClick={(e) => {
                                e.stopPropagation();
                              }}
                            />
                          </td>
                          <td className="px-4 py-2 whitespace-nowrap text-sm text-gray-900">{transaction.voucher_number || '&nbsp;'}</td>
                          <td className="px-4 py-2 whitespace-nowrap text-sm text-gray-900">{transaction.date}</td>
                          <td className="px-4 py-2 text-sm text-gray-900">{transaction.description}</td>
                          <td className="px-4 py-2 whitespace-nowrap text-sm text-right text-gray-900">
                            {transaction.amount < 0
                              ? `-${Math.abs(transaction.amount).toLocaleString('sv-SE', { minimumFractionDigits: 2 })}`
                              : transaction.amount.toLocaleString('sv-SE', { minimumFractionDigits: 2 })}
                          </td>
                          <td className="px-4 py-2 whitespace-nowrap text-center text-gray-400">
                            <button
                              onClick={(e) => { e.stopPropagation(); handleOpenComment(transaction.id, 'loaded'); }}
                              className={`hover:text-blue-500 ${transaction.comment ? 'text-blue-500' : ''}`}
                            >
                              <MessageSquare className="w-4 h-4" />
                            </button>
                          </td>
                        </tr>
                      ))
                    ) : (
                      <tr>
                        <td colSpan={6} className="px-4 py-8 text-center text-sm text-gray-500">
                          {loading ? 'Loading transactions...' : 'No loaded transactions found. Search to populate this table after creating and posting verifications.'}
                        </td>
                      </tr>
                    )}
                  </tbody>
                </table>
              </div>
            </div>
            <div className="border-t border-gray-300 mt-2">
              <div className="text-sm text-gray-600 text-right">
                {data.loadedTransactions.length > 0
                  ? `Account balance per ${data.reconciliationPeriodEnd || '-'}: ${calculateBalance(data.loadedTransactions).toLocaleString('sv-SE', { minimumFractionDigits: 2 })}`
                  : 'Account balance per -'}
              </div>
            </div>
          </div>
        </div>
      </div>

      {/* Bottom Summary Bar */}
      <div className="bg-white border-t border-gray-200 py-4">
        <div className="flex justify-between items-center">
          {/* Left Side - Accounting Transactions Summary */}
          <div className="flex items-center space-x-6">
            <Button
              variant="secondary"
              onClick={handleCancel}
              className="text-gray-700 border-gray-300 hover:bg-gray-50"
            >
              Cancel
            </Button>
            <div className="text-sm">
              <span className="text-gray-600">Balance: </span>
              <span className="font-medium">
                {data.accountingTransactions.length > 0 ? accountingBalance.toFixed(2) : '0.00'}</span>
            </div>
            <div className="text-sm">
              <span className="text-gray-600">Total selected: </span>
              <span className="font-medium text-[#f54a26]">
                {data.accountingTransactions.length > 0 ? accountingSelected.toFixed(2) : '0.00'}</span>
            </div>
            <div className="text-sm">
              <span className="text-gray-600">Closing balance: </span>
              <span className="font-medium">
                {data.accountingTransactions.length > 0 ? accountingClosing.toFixed(2) : '0.00'}</span>
            </div>
          </div>

          {/* Right Side - Loaded Transactions Summary */}
          <div className="flex items-center space-x-6">
            <div className="text-sm">
              <span className="text-gray-600">Balance: </span>
              <span className="font-medium">
                {data.loadedTransactions.length > 0 ? loadedBalance.toFixed(2) : '0.00'}</span>
            </div>
            <div className="text-sm">
              <span className="text-gray-600">Total selected: </span>
              <span className="font-medium text-[#f54a26]">
                {data.loadedTransactions.length > 0 ? loadedSelected.toFixed(2) : '0.00'}</span>
            </div>
            <div className="text-sm">
              <span className="text-gray-600">Closing balance: </span>
              <span className="font-medium">
                {data.loadedTransactions.length > 0 ? loadedClosing.toFixed(2) : '0.00'}</span>
            </div>
            <Button
              onClick={handleSave}
              className="bg-green-600 hover:bg-green-700 text-white"
              disabled={data.accountingTransactions.length === 0 || data.loadedTransactions.length === 0}
            >
              Save
            </Button>
          </div>
        </div>
      </div>

      {/* Reading History Popup */}
      {showHistoryPopup && (
        <div className="fixed inset-0 bg-black bg-opacity-50 flex items-center justify-center z-50">
          <div className="bg-white rounded-lg shadow-lg w-2/3 max-w-2xl p-0 relative">
            <div className="bg-blue-100 px-6 py-4 rounded-t-lg border-b border-gray-200">
              <div className="flex justify-between items-center">
                <h2 className="text-xl font-bold text-gray-800">Reading History</h2>
                <button
                  onClick={() => setShowHistoryPopup(false)}
                  className="text-gray-500 hover:text-gray-700"
                >
                  <X className="w-5 h-5" />
                </button>
              </div>
            </div>
            <div className="p-8">
              <p className="text-gray-600 text-center">No history available</p>
            </div>
          </div>
        </div>
      )}

      {/* Batch Reconciliation Popup */}
      {showBatchReconciliationPopup && (
        <div className="fixed inset-0 bg-black bg-opacity-50 flex items-center justify-center z-50">
          <div className="bg-white rounded-lg shadow-lg w-2/3 max-w-2xl p-0 relative">
            <div className="bg-[#9bbb48]/20 px-6 py-4 rounded-t-lg border-b border-gray-200">
              <div className="flex justify-between items-center">
                <h2 className="text-xl font-bold text-gray-800">MASS-RECONCILE ACCOUNTING TRANSACTIONS</h2>
                <button
                  onClick={() => setShowBatchReconciliationPopup(false)}
                  className="text-gray-500 hover:text-gray-700"
                >
                  <X className="w-5 h-5" />
                </button>
              </div>
            </div>
            <div className="p-6">
              <div className="space-y-4">
                <div>
                  <label className="block text-sm font-medium text-gray-700 mb-1">Date</label>
                  <div className="relative">
                    <Calendar className="absolute left-3 top-1/2 transform -translate-y-1/2 text-gray-400 w-4 h-4" />
                    <Input
                      type="date"
                      value={batchDate}
                      onChange={(e) => setBatchDate(e.target.value)}
                      className="pl-10 w-full"
                    />
                  </div>
                </div>
                <div>
                  <label className="block text-sm font-medium text-gray-700 mb-1">Account</label>
                  <Input
                    value={data.account}
                    readOnly
                    className="w-full bg-gray-50"
                  />
                </div>
                <div className="flex space-x-4 pt-4">
                  <Button
                    onClick={() => executeBatchReconciliation('undo')}
                    className="flex-1 bg-[#9bbb48] hover:bg-[#a9c56a] text-white"
                  >
                    Undo reconciliation
                  </Button>
                  <Button
                    onClick={() => executeBatchReconciliation('reconcile')}
                    className="flex-1 bg-[#5c6f2b] hover:bg-[#4a5a25] text-white"
                  >
                    Reconcile
                  </Button>
                </div>
              </div>
            </div>
          </div>
        </div>
      )}

      {/* Account Analysis Popup */}
      {showAccountAnalysisPopup && (
        <div className="fixed inset-0 bg-black bg-opacity-50 flex items-center justify-center z-50">
          <div className="bg-white rounded-lg shadow-lg w-2/3 max-w-2xl p-0 relative">
            <div className="bg-[#9bbb48]/20 px-6 py-4 rounded-t-lg border-b border-gray-200">
              <div className="flex justify-between items-center">
                <h2 className="text-xl font-bold text-gray-800">ACCOUNT ANALYSIS</h2>
                <button
                  onClick={() => setShowAccountAnalysisPopup(false)}
                  className="text-gray-500 hover:text-gray-700"
                >
                  <X className="w-5 h-5" />
                </button>
              </div>
            </div>
            <div className="p-6">
              <div className="space-y-6">
                <div>
                  <h3 className="text-lg font-semibold mb-4">Show Transactions</h3>
                  <div className="flex rounded-lg border border-gray-300 overflow-hidden mb-6">
                    <Button
                      className={`flex-1 ${activeTransactionFilter === 'Reconciled' ? 'bg-[#5c6f2b] text-white hover:bg-[#4a5a25]' : 'bg-[#9bbb48] text-gray-700 hover:bg-[#a9c56a]'} border-r border-gray-300 rounded-none`}
                      onClick={() => setActiveTransactionFilter('Reconciled')}
                    >
                      Reconciled
                    </Button>
                    <Button
                      className={`flex-1 ${activeTransactionFilter === 'Not reconciled' ? 'bg-[#5c6f2b] text-white hover:bg-[#4a5a25]' : 'bg-[#9bbb48] text-gray-700 hover:bg-[#a9c56a]'} border-r border-gray-300 rounded-none`}
                      onClick={() => setActiveTransactionFilter('Not reconciled')}
                    >
                      Not reconciled
                    </Button>
                    <Button
                      className={`flex-1 ${activeTransactionFilter === 'All' ? 'bg-[#5c6f2b] text-white hover:bg-[#4a5a25]' : 'bg-[#9bbb48] text-gray-700 hover:bg-[#a9c56a]'} rounded-none`}
                      onClick={() => setActiveTransactionFilter('All')}
                    >
                      All
                    </Button>
                  </div>
                </div>
                <div className="grid grid-cols-2 gap-4 mb-6">
                  <div>
                    <label className="block text-sm font-medium text-gray-700 mb-1">Date from</label>
                    <div className="relative">
                      <Calendar className="absolute left-3 top-1/2 transform -translate-y-1/2 text-gray-400 w-4 h-4" />
                      <Input
                        type="date"
                        value={analysisDateFrom}
                        onChange={(e) => setAnalysisDateFrom(e.target.value)}
                        className="pl-10 w-full"
                      />
                    </div>
                  </div>
                  <div>
                    <label className="block text-sm font-medium text-gray-700 mb-1">Date to</label>
                    <div className="relative">
                      <Calendar className="absolute left-3 top-1/2 transform -translate-y-1/2 text-gray-400 w-4 h-4" />
                      <Input
                        type="date"
                        value={analysisDateTo}
                        onChange={(e) => setAnalysisDateTo(e.target.value)}
                        className="pl-10 w-full"
                      />
                    </div>
                  </div>
                </div>
                <div className="flex space-x-4">
                  <Button
                    onClick={() => generateAccountAnalysisReport('screen')}
                    className="flex-1 bg-[#5c6f2b] hover:bg-[#4a5a25] text-white"
                  >
                    Show on screen
                  </Button>
                  <Button
                    onClick={() => generateAccountAnalysisReport('pdf')}
                    className="flex-1 bg-[#9bbb48] hover:bg-[#a9c56a] text-white"
                  >
                    Show PDF
                  </Button>
                  <Button
                    onClick={() => generateAccountAnalysisReport('txt')}
                    className="flex-1 bg-[#637e2f] hover:bg-[#526a27] text-white"
                  >
                    Show TXT
                  </Button>
                </div>
              </div>
            </div>
          </div>
        </div>
      )}

      {/* Reconciliation Report Popup */}
      {showReconciliationReportPopup && (
        <div className="fixed inset-0 bg-black bg-opacity-50 flex items-center justify-center z-50">
          <div className="bg-white rounded-lg shadow-lg w-2/3 max-w-2xl p-0 relative">
            <div className="bg-[#9bbb48]/20 px-6 py-4 rounded-t-lg border-b border-gray-200">
              <div className="flex justify-between items-center">
                <h2 className="text-xl font-bold text-gray-800">RECONCILIATION REPORT</h2>
                <button
                  onClick={() => setShowReconciliationReportPopup(false)}
                  className="text-gray-500 hover:text-gray-700"
                >
                  <X className="w-5 h-5" />
                </button>
              </div>
            </div>
            <div className="p-6">
              <div className="space-y-6">
                <div>
                  <h3 className="text-base font-medium mb-4">Total customer payments in</h3>
                  <div className="flex rounded-lg border border-gray-300 overflow-hidden mb-6">
                    <Button
                      className={`flex-1 h-10 ${customerPaymentsFilter === 'Yes' ? 'bg-[#5c6f2b] text-white hover:bg-[#4a5a25]' : 'bg-[#9bbb48] text-gray-700 hover:bg-[#a9c56a]'} border-r border-gray-300 rounded-none text-sm`}
                      onClick={() => setCustomerPaymentsFilter('Yes')}
                    >
                      Yes
                    </Button>
                    <Button
                      className={`flex-1 h-10 ${customerPaymentsFilter === 'No' ? 'bg-[#5c6f2b] text-white hover:bg-[#4a5a25]' : 'bg-[#9bbb48] text-gray-700 hover:bg-[#a9c56a]'} rounded-none text-sm`}
                      onClick={() => setCustomerPaymentsFilter('No')}
                    >
                      No
                    </Button>
                  </div>
                </div>
                <div>
                  <h3 className="text-base font-medium mb-4">Total supplier payments</h3>
                  <div className="flex rounded-lg border border-gray-300 overflow-hidden mb-6">
                    <Button
                      className={`flex-1 h-10 ${supplierPaymentsFilter === 'Yes' ? 'bg-[#5c6f2b] text-white hover:bg-[#4a5a25]' : 'bg-[#9bbb48] text-gray-700 hover:bg-[#a9c56a]'} border-r border-gray-300 rounded-none text-sm`}
                      onClick={() => setSupplierPaymentsFilter('Yes')}
                    >
                      Yes
                    </Button>
                    <Button
                      className={`flex-1 h-10 ${supplierPaymentsFilter === 'No' ? 'bg-[#5c6f2b] text-white hover:bg-[#4a5a25]' : 'bg-[#9bbb48] text-gray-700 hover:bg-[#a9c56a]'} rounded-none text-sm`}
                      onClick={() => setSupplierPaymentsFilter('No')}
                    >
                      No
                    </Button>
                  </div>
                </div>
                <div>
                  <h3 className="text-base font-medium mb-4">Total other items</h3>
                  <div className="flex rounded-lg border border-gray-300 overflow-hidden mb-6">
                    <Button
                      className={`flex-1 h-10 ${otherItemsFilter === 'Yes' ? 'bg-[#5c6f2b] text-white hover:bg-[#4a5a25]' : 'bg-[#9bbb48] text-gray-700 hover:bg-[#a9c56a]'} border-r border-gray-300 rounded-none text-sm`}
                      onClick={() => setOtherItemsFilter('Yes')}
                    >
                      Yes
                    </Button>
                    <Button
                      className={`flex-1 h-10 ${otherItemsFilter === 'No' ? 'bg-[#5c6f2b] text-white hover:bg-[#4a5a25]' : 'bg-[#9bbb48] text-gray-700 hover:bg-[#a9c56a]'} rounded-none text-sm`}
                      onClick={() => setOtherItemsFilter('No')}
                    >
                      No
                    </Button>
                  </div>
                </div>
                <div className="flex space-x-4">
                  <Button className="flex-1 bg-[#5c6f2b] hover:bg-[#4a5a25] text-white">
                    Show on screen
                  </Button>
                  <Button className="flex-1 bg-[#9bbb48] hover:bg-[#a9c56a] text-white">
                    Show PDF
                  </Button>
                  <Button className="flex-1 bg-[#637e2f] hover:bg-[#526a27] text-white">
                    Show TXT
                  </Button>
                </div>
              </div>
            </div>
          </div>
        </div>
      )}
      {/* Comment Popup (Notepad Style) */}
      {activeCommentRow && (
        <div className="fixed inset-0 bg-black bg-opacity-30 flex items-center justify-center z-[60]">
          <div className="bg-[#fef3c7] rounded-lg shadow-xl w-96 border border-[#f59e0b] overflow-hidden">
            <div className="bg-[#fde68a] px-4 py-2 border-b border-[#f59e0b] flex justify-between items-center">
              <span className="text-sm font-bold text-[#92400e] uppercase tracking-wider">Note Pad</span>
              <button onClick={() => setActiveCommentRow(null)} className="text-[#92400e] hover:text-black">
                <X className="w-4 h-4" />
              </button>
            </div>
            <div className="p-4">
              <textarea
                value={commentText}
                onChange={(e) => setCommentText(e.target.value)}
                placeholder="Write your comment here..."
                className="w-full h-40 bg-transparent border-none focus:ring-0 text-gray-800 resize-none font-mono text-sm leading-6"
                style={{
                  backgroundImage: 'linear-gradient(#d1d5db 1px, transparent 1px)',
                  backgroundSize: '100% 1.5rem',
                  lineHeight: '1.5rem'
                }}
                autoFocus
              />
              <div className="flex justify-end space-x-2 mt-4 pt-2 border-t border-[#f59e0b]/30">
                <Button
                  variant="ghost"
                  size="sm"
                  onClick={() => setActiveCommentRow(null)}
                  className="text-[#92400e] hover:bg-[#fde68a] text-xs h-7"
                >
                  Cancel
                </Button>
                <Button
                  size="sm"
                  onClick={handleSaveComment}
                  className="bg-[#d97706] hover:bg-[#b45309] text-white text-xs h-7"
                >
                  Save
                </Button>
              </div>
            </div>
          </div>
        </div>
      )}

      {/* Toast Notification */}
      {toast.visible && (
        <div className={`fixed bottom-4 right-4 z-[70] flex items-center space-x-2 px-4 py-2 rounded-lg shadow-lg text-white transition-opacity duration-300 ${toast.type === 'success' ? 'bg-[#5c6f2b]' :
          toast.type === 'error' ? 'bg-red-600' : 'bg-blue-600'
          }`}>
          {toast.type === 'success' ? <CheckCircle className="w-4 h-4" /> : <AlertCircle className="w-4 h-4" />}
          <span className="text-xs font-medium">{toast.message}</span>
        </div>
      )}

      {/* Hidden file input */}
      <input
        type="file"
        ref={fileInputRef}
        className="hidden"
        onChange={() => { }} // Add file handling logic here if needed
      />
    </div>
  );
};
